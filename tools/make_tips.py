#!/usr/bin/env python3
"""Turns the renderer's pictures (target/tips/raw, made by `cargo test -p fusion-app render_tutorial_pictures -- --ignored`)
into small JPEGs in crates/app/assets/tips and writes crates/app/src/tips_index.rs, the table the tooltips read."""
import pathlib, subprocess, sys

root = pathlib.Path(__file__).resolve().parent.parent
raw, out = root / "target/tips/raw", root / "crates/app/assets/tips"
out.mkdir(parents=True, exist_ok=True)
for old in out.glob("*.jpg"):
    old.unlink()
names = {}
for png in sorted(raw.glob("*.png")):
    stem = png.stem
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(png), "-vf", "scale=420:-1:flags=lanczos", "-q:v", "4", str(out / f"{stem}.jpg")], check=True)
    tool, tag = stem.rsplit("_", 1)
    names.setdefault(tool, {})[tag] = stem
lines = ["// generated by tools/make_tips.py — do not edit", "pub fn bytes(id: &str) -> Option<(Option<&'static [u8]>, &'static [u8])> {", "    match id {"]
for tool, tags in sorted(names.items()):
    before = f'Some(include_bytes!("../assets/tips/{tags["before"]}.jpg") as &[u8])' if "before" in tags else "None"
    lines.append(f'        "{tool}" => Some(({before}, include_bytes!("../assets/tips/{tags["after"]}.jpg"))),')
lines += ["        _ => None,", "    }", "}", ""]
(root / "crates/app/src/tips_index.rs").write_text("\n".join(lines))
print(len(names), "tools,", sum(len(v) for v in names.values()), "pictures")
