from drv import *
import subprocess, sys, time

launch()                                   # приложение на главной странице
rec = subprocess.Popen(
    ["ffmpeg", "-y", "-loglevel", "error", "-f", "x11grab", "-framerate", "15", "-video_size", "1360x850",
     "-i", ":99+0,0", "-c:v", "libx264", "-preset", "veryfast", "-crf", "26", "-pix_fmt", "yuv420p", f"{S}/raw.mp4"],
    stdin=subprocess.PIPE)
time.sleep(1.2)
start_clock()


def cap(t, d=4.5):
    say(t, d)


try:
    # ---------------- 1. Главная страница
    cap("Genix — параметрическая 3D-САПР. Главная страница: проекты и примеры", 5)
    move(700, 500, 20); wait(3.0)
    cap("Боковая панель раскрывается при наведении", 4)
    move(30, 330, 25); wait(3.5)
    move(500, 420, 20); wait(0.5)
    cap("Поиск и фильтры по проектам", 4)
    click(897, 211, pause=3.5)
    click(897, 211, pause=1.0)
    cap("Готовые примеры с превью моделей", 4)
    move(218, 466, 25); wait(3.5)

    # ---------------- 2. Настройки
    cap("Настройки: тема, акцентный цвет, управление, материал, автосохранение", 5)
    click(39, 331, pause=3.0)
    click(373, 210, pause=1.8)
    click(335, 210, pause=1.8)
    click(297, 210, pause=1.8)
    cap("Выход из аккаунта — здесь же, проекты на компьютере не удаляются", 4)
    move(180, 735, 20); wait(3.5)
    click(39, 140, pause=1.5)

    # ---------------- 3. Новый проект
    cap("Создаём новый проект", 3)
    click(160, 145, pause=0.5)
    for i in range(8):
        move(500 + i * 9, 520); time.sleep(0.45)
    click(150, 20, pause=1.5)
    focus()
    wait(1.0)

    cap("Стены: параллелепипед 120 × 100 × 60 мм — размеры вводятся точно", 6)
    box(120, 100, 60, 0, 0, 0, "new", confirm=False)
    wait(1.5)
    click(1134, 452, pause=1.5)
    key("f", 1.5)
    cap("Вырезаем внутренний объём — дом будет пустым внутри", 5)
    box(110, 90, 60, 5, 5, 5, "cut")
    key("f", 2.0)
    cap("Операции: новое тело, объединить, вырезать, пересечь", 4)
    wait(2.5)
    cap("Дверь и окна — вырезаем параллелепипеды", 5)
    box(20, 7, 42, 50, -1, 5, "cut")
    key("f", 1.0)
    box(20, 7, 20, 15, -1, 25, "cut")
    box(20, 7, 20, 85, -1, 25, "cut")
    box(7, 20, 20, -1, 40, 25, "cut")
    box(7, 20, 20, 114, 40, 25, "cut")
    key("f", 2.0)
    wait(2.0)

    # ---------------- 4. Крыша: чертёж и выдавливание
    cap("Крыша: новый чертёж на плоскости XZ", 4)
    click(105, 70, pause=1.5)
    click(1190, 265, pause=2.5)
    cap("Инструмент «Линия»: рисуем треугольник — профиль крыши", 5)
    P = lambda x, z: (int(432 + 3.65 * x), int(570 - 3.65 * z))
    A, B, C = P(-10, 60), P(130, 60), P(60, 90)
    click(*A, pause=1.0); click(*B, pause=1.0); click(*C, pause=1.0); click(*A, pause=1.2)
    key("Escape", 1.0)
    move(700, 700); wait(1.5)
    cap("Контур замкнут — программа нашла профиль. Завершаем чертёж", 4)
    click(952, 70, pause=2.5)
    cap("Выдавливание профиля на 100 мм", 4)
    click(185, 70, pause=1.5)
    click(783, 453, pause=1.5)
    click(1241, 301, pause=0.3); key("ctrl+a", 0.2); typ("100", 0.3); key("Return", 0.8)
    click(1188, 330, pause=1.5)            # обратное направление (после ввода глубины)
    click(1245, 358, pause=0.8)
    click(1240, 420, pause=1.0)            # операция: объединить
    wait(2.0)
    click(1122, 405, pause=2.5)
    key("f", 2.0)

    # ---------------- 5. Окно в крыше и дымоход
    cap("Окно в крыше — вырез сквозь скат", 4)
    box(15, 30, 27, 20, 35, 58, "cut")
    key("f", 2.0)
    cap("Дымоход: параллелепипед, объединённый с крышей", 4)
    box(12, 12, 45, 85, 70, 55, "join")
    key("f", 2.0)
    cap("Канал дымохода — ещё один вырез", 4)
    box(6, 6, 50, 88, 73, 56, "cut")
    key("f", 2.5)

    # ---------------- 6. Скругление
    cap("Скругление рёбер: подсвечивается ребро под курсором, радиус задаётся числом", 6)
    click(497, 66, pause=1.5)
    move(680, 700, 20); wait(1.5)
    click(680, 700, pause=1.5)
    wait(1.5)
    click(1123, 412, pause=3.0)

    # ---------------- 7. Свойства и материал
    cap("Выбранное тело: габариты, объём, площадь и масса по материалу", 5)
    click(760, 560, pause=2.5)
    click(1172, 311, pause=1.5)
    cap("Реальные материалы: плотность, цвет и блеск", 4)
    click(1130, 516, pause=2.5)            # дерево
    wait(2.0)
    click(1172, 311, pause=1.5)
    click(1130, 429, pause=2.5)            # латунь
    wait(2.0)
    click(1172, 311, pause=1.5)
    click(1130, 516, pause=2.0)            # снова дерево
    click(300, 300, pause=1.0)

    # ---------------- 8. Вращение вида
    cap("Вращение вида левой кнопкой мыши, колесо — масштаб", 5)
    drag(300, 280, 620, 300, steps=45, pause=1.0)
    drag(620, 300, 380, 320, steps=45, pause=1.0)
    drag(300, 300, 300, 480, steps=40, pause=1.5)
    cap("Вид сверху: окно в крыше и дымоход", 4)
    wait(2.5)
    drag(300, 480, 300, 330, steps=40, pause=1.0)
    for i in range(3):
        sh("xdotool", "click", "4"); time.sleep(0.4)
    wait(1.5)
    for i in range(3):
        sh("xdotool", "click", "5"); time.sleep(0.4)
    key("f", 2.0)

    # ---------------- 9. История построения
    cap("История построения: любой шаг можно отмотать и изменить", 5)
    click(66, 832, pause=2.0)
    for i in range(3):
        click(143, 832, pause=1.4)
    cap("Три шага: стены, пустой объём и дверь — дом пустой внутри", 5)
    wait(3.0)
    click(183, 832, pause=2.5)
    cap("Воспроизведение: модель строится шаг за шагом", 4)
    click(66, 832, pause=1.5)
    click(258, 832, pause=1.0)
    wait(16.0)
    click(183, 832, pause=2.0)
    key("f", 2.0)

    # ---------------- 10. Финал
    cap("Экспорт: STL и 3MF для 3D-печати, OBJ, снимок PNG без фона", 5)
    click(40, 17, pause=1.5)
    wait(3.0)
    key("Escape", 1.0)
    cap("Genix — готовый дом с дверями, окнами, окном в крыше и дымоходом", 6)
    drag(300, 300, 520, 300, steps=60, pause=1.0)
    wait(5.0)
finally:
    end = now()
    rec.stdin.write(b"q"); rec.stdin.flush()
    rec.wait(timeout=60)
    write_srt(f"{S}/demo.srt")
    print("recorded", end)
